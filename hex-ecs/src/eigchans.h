#ifndef HEX_EIGCHANS
#define HEX_EIGCHANS

#include <map>
#include <vector>

#include "hex-matrix.h"

#include "ang.h"
#include "inout.h"

class Eigchans
{
    public:

        // calculate angular momentum eigenchannels
        void calc(InputFile const& inp, std::vector<std::pair<int,int>> const& ang);

        // eigenvalues of the 1/2r² potential matrix per n-shell
        std::map<int, rArray> eigvals;

        // generalized angular momenta calculated from "eigvals" per n-shell
        std::map<int, cArray> eigmoms;

        // eigenvectors of the 1/2r² potential matrix per n-shell
        std::map<int, ColMatrix<Real>> eigvecs;
};

#endif  // HEX_EIGCHANS
